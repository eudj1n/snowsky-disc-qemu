"""Assemble the local browser bundle inside the prototype build container."""
import hashlib
import json
import re
from pathlib import Path
import shutil
import subprocess

from firmware.profile import selected_profile, validate

REPO = Path(__file__).resolve().parents[2]
WORK = REPO / 'work/browser-disc'
SOURCE = REPO / 'experiments/browser'


def run(*args, cwd=None):
    subprocess.run([str(a) for a in args], cwd=cwd, check=True)


def digest(path):
    with path.open('rb') as f:
        return hashlib.file_digest(f, 'sha256').hexdigest()


def refresh_ui():
    web = WORK / 'www'
    web.mkdir(exist_ok=True)
    assets = {f.name: f.read_bytes() for f in (SOURCE / 'static').iterdir()}
    # Presentation only: no Viewer server/runtime is needed by the standalone VM.
    assets['device.css'] = (REPO / 'viewer/static/device.css').read_bytes()
    revision = hashlib.sha256(b''.join(name.encode() + data for name, data in sorted(assets.items()))).hexdigest()[:12]
    for name, data in assets.items():
        # A refresh must invalidate the whole module graph, not just index.html.
        text = data.decode()
        for asset in assets:
            text = re.sub(r"([\"'])(\./)?" + re.escape(asset) + r"\1",
                          lambda m: m[1] + (m[2] or '') + asset + '?v=' + revision + m[1], text)
        (web / name).write_text(text)



def bundle():
    # Stage is exclusively generated by this command, never an interactive rootfs.
    stage = WORK / 'vm-root'
    if stage.exists():
        shutil.rmtree(stage)
    stage.mkdir()
    demo = WORK / 'jslinux-2019-12-21'
    run('debugfs', '-R', f'rdump / {stage}', demo / 'root-riscv64.bin')
    disc = stage / 'disc'
    disc.mkdir()
    run('tar', '-xf', WORK / 'disc-prepared.tar', '-C', disc)
    profile = selected_profile()
    validate(disc, profile)
    # No native build-container binary is needed inside the MIPS filesystem.
    (disc / 'dev/fb0').write_bytes(bytes(360 * 1080 * 4))
    for event in ('event0', 'event1'):
        (disc / 'dev/input' / event).write_bytes(b'')
    (disc / 'emu/fb-live').write_bytes(b'\xff')
    (disc / 'emu/power-request').write_text('0')
    for name, value in [('address', '02:00:00:00:00:01\n'), ('operstate', 'down\n')]:
        path = disc / 'sys/class/net/eth1' / name
        path.chmod(0o644)
        path.write_text(value)
    for path in ('exchange', 'var/log', 'usr/bin'):
        (stage / path).mkdir(parents=True, exist_ok=True)
    package = WORK / 'qemu-package'
    if not package.exists():
        run('dpkg-deb', '-x', WORK / 'downloads/qemu-user_riscv64.deb', package)
    shutil.copy2(package / 'usr/bin/qemu-mipsel', stage / 'usr/bin/qemu-mipsel')
    shutil.copy2(SOURCE / 'guest-init.sh', stage / 'sbin/init')
    (stage / 'sbin/init').chmod(0o755)
    run('riscv64-linux-gnu-gcc', '-O2', '-static', '-Wall', '-Wextra', '-Werror',
        SOURCE / 'guest-bridge.c', '-o', stage / 'usr/bin/disc-bridge')
    tiny = WORK / 'tinyemu-2019-12-21'
    run('make', '-j4', 'CONFIG_FS_NET=', 'CONFIG_SDL=', 'CONFIG_X86EMU=',
        'CONFIG_INT128=', 'CONFIG_SLIRP=', 'temu', 'splitimg', 'build_filelist', cwd=tiny)
    image = WORK / 'disc-root.bin'
    with image.open('wb') as f:
        f.truncate(256 * 1024 * 1024)
    run('mkfs.ext2', '-q', '-F', '-b', '4096', '-d', stage, image)
    web = WORK / 'www'
    web.mkdir(exist_ok=True)
    refresh_ui()
    for name in ('bbl64.bin', 'riscvemu64-wasm.wasm'):
        shutil.copy2(demo / name, web / name)
    # Replace only the download callback in the pinned, precompiled TinyEMU glue.
    # The VM's 9P export becomes a local worker message instead of a file download.
    glue = (demo / 'riscvemu64-wasm.js').read_text()
    start = glue.index('function _fs_export_file(')
    end = glue.index('function _fs_wget_update_downloading(', start)
    glue = glue[:start] + ('function _fs_export_file(filename,buf,len){'
        'discExport(Pointer_stringify(filename),HEAPU8.subarray(buf,buf+len));}') + glue[end:]
    (web / 'riscvemu64-wasm.js').write_text(glue)
    shutil.copy2(WORK / 'kernel-browser.bin', web / 'kernel.bin')
    (web / 'disk').mkdir(exist_ok=True)
    run(tiny / 'splitimg', image, web / 'disk', '256')
    exchange = WORK / 'exchange-seed'
    if exchange.exists():
        shutil.rmtree(exchange)
    exchange.mkdir()
    run(tiny / 'build_filelist', '-m', '16', exchange, web / 'exchange')
    config = dict(version=1, machine='riscv64', memory_size=512, bios='bbl64.bin',
                  kernel='kernel.bin', cmdline='console=hvc0 root=/dev/vda rw',
                  drive0=dict(file='disk/blk.txt'), fs0=dict(file='exchange'))
    (web / 'disc.cfg').write_text(json.dumps(config, indent=2) + '\n')
    # Native TinyEMU shares the CPU implementation; useful preflight, not browser evidence.
    native = dict(config, bios=str(web / 'bbl64.bin'), kernel=str(web / 'kernel.bin'),
                  drive0=dict(file=str(image)), fs0=dict(file=str(WORK / 'exchange-root')))
    (WORK / 'disc-native.cfg').write_text(json.dumps(native, indent=2) + '\n')
    manifest = dict(firmware_version=profile['version'], guest_arch='riscv64',
                    firmware_arch='mipsel', guest_ram_mib=512,
                    root_image_sha256=digest(image), kernel_sha256=digest(web / 'kernel.bin'),
                    qemu_sha256=digest(stage / 'usr/bin/qemu-mipsel'))
    (web / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    shutil.copy2(tiny / 'MIT-LICENSE.txt', web / 'TinyEMU-LICENSE.txt')
    print(f'Local browser bundle: {web}', flush=True)


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--ui-only', action='store_true')
    args = parser.parse_args()
    if args.ui_only:
        if not (WORK / 'www/manifest.json').exists():
            parser.error('Build the prototype first')
        refresh_ui()
    else:
        bundle()
